function renderGrid(lang, title) {
	const heading = lang === 'en-US' ? 'My projects' : 'Mes projets';
	return `
		<div id="projects-page">
			<h1>${heading}</h1>
			<div id="projects-grid">
				${PROJECTS.map(p => `
					<div class="project-card" data-project="${p.id}">
						<img src="${p.image}" alt="${p.title}">
						<div class="project-card-title">${p.title}</div>
					</div>`).join('')}
			</div>
		</div>
		${PROJECTS.map(p => `
			<div id="project-detail-${p.id}" class="project-detail-view">
				<a class="back-to-grid">${BACK_SVG} ${lang === 'en-US' ? 'Back' : 'Retour'}</a>
				<img class="main-image" src="${p.image}" alt="${p.title}">
				<h1>${p.title}</h1>
				<div class="project-tags">
					${p.tags.map(t => `<span class="tag">${t}</span>`).join('')}
				</div>
				${p.content[lang] || p.content['fr-FR']}
			</div>`).join('')}
	`;
}

